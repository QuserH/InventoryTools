    public static string CurrentLanguage { get; set; } = "zh-CN";

    static LocalizationService()
    {
        // Route CriticalCommonLib enum helpers (bag/container names etc.) through this dictionary.
        SharedLocalization.Translate = Get;
        // Route OtterGui widget strings (hotkey selectors, file selector, etc.) through this dictionary.
        OtterGui.Localization.CommonLocalization.Translate = Get;
    }

    public static string Get(string? english)
    {
        if (string.IsNullOrEmpty(english))
        {
            return english ?? string.Empty;
        }

        if (SharedLocalization.Translate == null)
        {
            SharedLocalization.Translate = Get;
        }

        if (!IsSimplifiedChinese)
        {
            return english;
        }

        SplitImGuiId(english, out string visible, out string id);
        string translated = CoreTranslations.TryGetValue(visible, out string? value)
            ? value
            : visible;
        return translated + id;
    }

    public static string Format(string english, params object?[] args) =>
        string.Format(CultureInfo.CurrentCulture, Get(english), args);

    public static string Dynamic(string english, IReadOnlyDictionary<string, string> translations)
    {
        if (!IsSimplifiedChinese)
        {
            return english;
        }

        SplitImGuiId(english, out string visible, out string id);
        return (translations.TryGetValue(visible, out string? translated) ? translated : visible) + id;
    }

    private static void SplitImGuiId(string value, out string visible, out string id)
    {
        int stableId = value.IndexOf("###", StringComparison.Ordinal);
        int hiddenId = stableId >= 0 ? stableId : value.IndexOf("##", StringComparison.Ordinal);
        if (hiddenId < 0)
        {
            visible = value;
            id = string.Empty;
            return;
        }

        visible = value[..hiddenId];
        id = value[hiddenId..];
    }

    private static bool IsSimplifiedChinese =>
        CurrentLanguage.Equals("zh-CN", StringComparison.OrdinalIgnoreCase) ||
        CurrentLanguage.Equals("zh-Hans", StringComparison.OrdinalIgnoreCase) ||
        CurrentLanguage.Equals("zh", StringComparison.OrdinalIgnoreCase);
