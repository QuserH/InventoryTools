    public static string Ui(string english)
    {
        if (!IsSimplifiedChinese)
        {
            return english;
        }

        SplitImGuiId(english, out string visible, out string id);
        if (UiTranslations.TryGetValue(visible, out string? translated))
        {
            return translated + id;
        }

        return Get(english);
    }
